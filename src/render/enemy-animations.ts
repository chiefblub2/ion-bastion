/// <reference types="vite/client" />
import type { ContentPack, EnemyId, MissionDefinition } from "../core/types";
import manifest from "../../assets-src/enemy-animations/manifest.json";
import { ANIMATION_BOUNDS } from "./enemy-animation-bounds";
import { artFor, type EnemyArt } from "./enemy-art";
/**
 * Frame-by-frame enemy animations (render only): which enemy types have spritesheets and how each clip plays.
 * Every animated type has one sheet, `public/assets/enemy-animations/<id>.png`: a grid of `ANIMATION_COLUMNS` ×
 * `ANIMATION_ROWS` square cells, one clip per row (idle, move, hurt, death), frames from the left, unused cells empty;
 * Phaser numbers its frames row by row, so a clip is its first frame (`start`) and a count. The sheets are generated
 * from the supplied pack in `assets-src/enemy-animations/` (`manifest.json`, version 2, which also decides which types
 * are registered) by `scripts/normalize-enemy-animations.ts`, which re-cuts its misaligned frames into 256 px cells
 * (2048 × 1024). Sheets load per mission (`missionAnimationTypes`), since each one decodes to 8 MiB of texture.
 * The static art (`enemy-art.ts`) stays authoritative for scale, pose, heading offset and shift; an animated body
 * only swaps in the cell's own measured visible bounds (`ANIMATION_BOUNDS`, generated by
 * `scripts/audit-enemy-animations.ts -- --write`), so it shows at the same visible size and centre as the static art.
 */
export const ANIMATION_STATES = ["idle", "move", "hurt", "death"] as const;
export type EnemyAnimationState = (typeof ANIMATION_STATES)[number];
export interface AnimationClip {
  /** Phaser texture key of the enemy's sheet, shared by its clips: `enemy:<id>:anim`. */
  texture: string;
  /** File under `public/`, without the base path. */
  path: string;
  frameWidth: number;
  frameHeight: number;
  /** Index of the clip's first frame in its sheet (row × `ANIMATION_COLUMNS`). */
  start: number;
  frames: number;
  fps: number;
  /** Idle and move loop; hurt and death play once and hold their last frame. */
  loop: boolean;
}
/** The clips of one enemy type; any state may be missing (it falls back, see `animate`). */
export type EnemyAnimationSet = Partial<Record<EnemyAnimationState, AnimationClip>>;
/** Cell edge and grid of every game sheet. */
export const ANIMATION_CELL = 256;
export const ANIMATION_COLUMNS = 8;
export const ANIMATION_ROWS = 4;
/** One clip of the source pack: its row in the grid, its frame count from the left, and its timing. */
export interface ManifestClip {
  row: number;
  frames: number;
  fps: number;
  loop: boolean;
}
/**
 * The animation pack (`assets-src/enemy-animations/manifest.json`, version 2), the single source of which types are
 * animated and how their clips play. `animations` is the default layout; an enemy's own `animations` overrides
 * single fields of a state, or drops a state with `null` (it then falls back, see `animate`). An enemy with
 * `disabled` (the reason) keeps its source in the pack but is not normalized or registered, so it shows static art.
 */
export interface AnimationManifest {
  version: 2;
  description?: string;
  /** Source cell size and grid (the game sheets use `ANIMATION_CELL` with the same grid). */
  frameWidth: number;
  frameHeight: number;
  columns: number;
  rows: number;
  animations: Record<EnemyAnimationState, ManifestClip & { start?: number; end?: number }>;
  enemies: Record<string, { sheet: string; disabled?: string; animations?: Partial<Record<EnemyAnimationState, Partial<ManifestClip> | null>> }>;
}
export const ANIMATION_MANIFEST = manifest as AnimationManifest;
/** The clips an enemy's manifest entry declares: the defaults with its own overrides; null for a dropped state. */
export function manifestClips(entry: AnimationManifest["enemies"][string], pack: AnimationManifest = ANIMATION_MANIFEST): Partial<Record<EnemyAnimationState, ManifestClip>> {
  return Object.fromEntries(
    ANIMATION_STATES.flatMap((state) => {
      const own = entry.animations?.[state];
      if (own === null) return [];
      const { row, frames, fps, loop } = { ...pack.animations[state], ...own };
      return [[state, { row, frames, fps, loop }]];
    }),
  );
}
/** Types the manifest enables (not `disabled`), in manifest order. */
export const manifestTypes = (pack: AnimationManifest = ANIMATION_MANIFEST) => Object.keys(pack.enemies).filter((id) => !pack.enemies[id].disabled) as EnemyId[];
export const sheetKey = (id: EnemyId) => `enemy:${id}:anim`;
/**
 * Every animated enemy type and its clips, from the manifest. Adding one is its source sheet plus a manifest entry,
 * then `scripts/normalize-enemy-animations.ts` and `scripts/audit-enemy-animations.ts -- --write` (identity, frames,
 * bounds). The type must have static art as well.
 */
export const ENEMY_ANIMATIONS: Readonly<Partial<Record<EnemyId, EnemyAnimationSet>>> = Object.fromEntries(
  manifestTypes().map((id) => [
    id,
    Object.fromEntries(
      Object.entries(manifestClips(ANIMATION_MANIFEST.enemies[id])).map(([state, { row, frames, fps, loop }]) => [
        state,
        { texture: sheetKey(id), path: `assets/enemy-animations/${id}.png`, frameWidth: ANIMATION_CELL, frameHeight: ANIMATION_CELL, start: row * ANIMATION_COLUMNS, frames, fps, loop },
      ]),
    ),
  ]),
);
/** The clips of an enemy type, or undefined for a type without animations. */
export const animationsFor = (type: EnemyId): EnemyAnimationSet | undefined => ENEMY_ANIMATIONS[type];
/** Every registered clip. */
export const allClips = (): AnimationClip[] => Object.values(ENEMY_ANIMATIONS).flatMap((set) => ANIMATION_STATES.flatMap((s) => (set![s] ? [set![s]!] : [])));
/** One sheet per animated type, for loading: its texture, file and cell size (the first clip's). */
export const allSheets = () => [...new Map(allClips().map((c) => [c.texture, { texture: c.texture, path: c.path, frameWidth: c.frameWidth, frameHeight: c.frameHeight }])).values()];
/**
 * The animated types a mission can field: its wave groups plus every type they lay or split into (any trait naming
 * a `type`: `splitOnDeath`, `brood`), followed transitively. Versus sends come from the same waves. A type missed here
 * would only show its static art.
 */
export function missionAnimationTypes(mission: Pick<MissionDefinition, "waves">, content: Pick<ContentPack, "enemies">): Set<EnemyId> {
  const found = new Set<EnemyId>(),
    queue: EnemyId[] = mission.waves.flatMap((w) => w.groups.map((g) => g.type));
  while (queue.length) {
    const type = queue.shift()!;
    if (found.has(type) || !content.enemies[type]) continue;
    found.add(type);
    for (const t of content.enemies[type].traits ?? []) if ("type" in t && typeof t.type === "string") queue.push(t.type as EnemyId);
  }
  return new Set([...found].filter((type) => ENEMY_ANIMATIONS[type]));
}
/**
 * Which sheets a scene loads and which it releases: with `types`, the sheets of those types that are not loaded yet
 * (`has`) and the loaded sheets of every other type; without, every sheet not loaded yet, releasing none.
 */
export function sheetPlan(types: ReadonlySet<EnemyId> | undefined, has: (texture: string) => boolean) {
  const sheets = allSheets(),
    wanted = new Set(types ? [...types].map(sheetKey) : sheets.map((s) => s.texture));
  return { load: sheets.filter((s) => wanted.has(s.texture) && !has(s.texture)), release: sheets.filter((s) => !wanted.has(s.texture) && has(s.texture)).map((s) => s.texture) };
}
/** The sheet frame (Phaser frame index) of a clip's frame `i`. */
export const sheetFrame = (clip: Pick<AnimationClip, "start">, i: number) => clip.start + i;
/** Why a clip cannot play (bad timing or size), or undefined for a usable one. */
export function clipError(clip: AnimationClip): string | undefined {
  if (!Number.isInteger(clip.frames) || clip.frames < 1) return `frames must be a positive integer (${clip.frames})`;
  if (!Number.isFinite(clip.fps) || clip.fps <= 0 || clip.fps > 60) return `fps must be in (0, 60] (${clip.fps})`;
  // A clip lies on one row of its sheet.
  if (!Number.isInteger(clip.start) || clip.start < 0 || clip.start + clip.frames > ANIMATION_COLUMNS * ANIMATION_ROWS || (clip.start % ANIMATION_COLUMNS) + clip.frames > ANIMATION_COLUMNS)
    return `frames ${clip.start}–${clip.start + clip.frames - 1} do not lie on one row of the ${ANIMATION_COLUMNS} × ${ANIMATION_ROWS} sheet`;
  if (!Number.isInteger(clip.frameWidth) || !Number.isInteger(clip.frameHeight) || clip.frameWidth < 1 || clip.frameHeight < 1) return "frame size must be positive integers";
  // A non-square cell would distort under the square placement of `placeArt`.
  if (clip.frameWidth !== clip.frameHeight) return `cells must be square (${clip.frameWidth}×${clip.frameHeight})`;
  return undefined;
}
/** Seconds one pass of a clip takes. */
export const clipDuration = (clip: Pick<AnimationClip, "frames" | "fps">) => clip.frames / clip.fps;
/**
 * The frame of the clip (0-based, `sheetFrame` turns it into the sheet's) shown `elapsed` seconds after it started:
 * a loop wraps, a one-shot clip holds its last frame. Negative or non-finite times show the first frame.
 */
export function clipFrame(clip: Pick<AnimationClip, "frames" | "fps" | "loop">, elapsed: number) {
  if (!(elapsed > 0) || !Number.isFinite(elapsed)) return 0;
  const i = Math.floor(elapsed * clip.fps + 1e-9);
  return clip.loop ? i % clip.frames : Math.min(i, clip.frames - 1);
}
/**
 * Placement data of an animated body: the type's static art tuning (scale, pose, angle offset, shift) with the
 * animation cell's measured bounds, so `placeArt` sizes and centres the cell like the static image. Undefined
 * without static art or without animations.
 */
export function animationArt(type: EnemyId): EnemyArt | undefined {
  const art = artFor(type);
  if (!art || !ENEMY_ANIMATIONS[type]) return undefined;
  return { ...art, bounds: ANIMATION_BOUNDS[type] ?? art.bounds };
}
/** URL of a sheet below the configured Vite base path. */
export const clipUrl = (clip: Pick<AnimationClip, "path">, base: string = import.meta.env.BASE_URL) => `${base.endsWith("/") ? base : `${base}/`}${clip.path}`;
